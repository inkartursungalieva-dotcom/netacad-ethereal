def translate_po_file(po_path):
    with open(po_path, 'r', encoding='utf-8') as f:
        content = f.read()
    
    # Replace msgstr entries
    for russian, kazakh in translation_dict.items():
        # Find pattern: msgid "russian" followed by msgstr ""
        pattern = re.compile(rf'msgid "{re.escape(russian)}"\s*msgstr ""')
        replacement = f'msgid "{russian}"\nmsgstr "{kazakh}"'
        content = pattern.sub(replacement, content)
    
    # Write back
    with open(po_path, 'w', encoding='utf-8') as f:
        f.write(content)
    
    print(f"Translations applied to {po_path}")

