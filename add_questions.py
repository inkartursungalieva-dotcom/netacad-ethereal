def add_questions_to_module(module, questions):
    for q_data in questions:
        question = Question.objects.create(
            module=module,
            text=q_data['text'],
            text_kk=q_data['text_kk'],
            difficulty=q_data['difficulty'],
            type='multiple_choice'
        )

        for idx, (choice_ru, choice_kk, is_correct) in enumerate(q_data['choices']):
            Choice.objects.create(
            question=question,
            text=choice_ru,
            text_kk=choice_kk,
            is_correct=is_correct,
            order=idx
        )

